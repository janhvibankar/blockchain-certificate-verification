/**
 * Shows a specific page section and hides all others.
 * @param {string} sectionName - One of: home, issue, verify, admin, about
 */
function showSection(sectionName) {
  // Hide all sections
  document.querySelectorAll(".page-section").forEach(function (el) {
    el.classList.remove("active");
  });

  // Update nav link active state
  document.querySelectorAll(".nav-links a[data-section]").forEach(function (link) {
    link.classList.remove("active");
    if (link.getAttribute("data-section") === sectionName) {
      link.classList.add("active");
    }
  });

  // Show the selected section
  const target = document.getElementById("section" + capitalize(sectionName));
  if (target) target.classList.add("active");

  // Close mobile menu
  document.getElementById("navLinks").classList.remove("open");

  // Scroll to top
  window.scrollTo(0, 0);

  // Run section-specific logic
  if (sectionName === "admin") {
    loadAdminDashboard();
  }
  if (sectionName === "issue") {
    updateIssuePageState();
  }
}

function capitalize(str) {
  return str.charAt(0).toUpperCase() + str.slice(1);
}

