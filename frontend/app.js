/**
 * Loads the admin dashboard with certificate data from blockchain.
 */
async function loadAdminDashboard() {
  const adminContent   = document.getElementById("adminContent");
  const notAdminAlert  = document.getElementById("adminNotAdminAlert");

  // Check if admin
  if (!isWalletConnected || !isContractOwner) {
    adminContent.classList.remove("visible");
    notAdminAlert.classList.add("visible");
    return;
  }

  adminContent.classList.add("visible");
  notAdminAlert.classList.remove("visible");

  if (!contract) {
    console.error("Contract not initialized");
    return;
  }

  showElement("adminLoading");

  try {
    // Load stats
    const totalIssued  = await contract.totalCertificatesIssued();
    const totalRevoked = await contract.totalCertificatesRevoked();

    document.getElementById("adminStatWallet").textContent  = shortenAddress(currentAccount);
    document.getElementById("adminStatIssued").textContent  = totalIssued.toString();
    document.getElementById("adminStatRevoked").textContent = totalRevoked.toString();

    // Load all certificate IDs
    const certIds = await contract.getAllCertificateIds();

    // Populate table
    const tbody = document.getElementById("certTableBody");
    tbody.innerHTML = "";

    if (!certIds || certIds.length === 0) {
      tbody.innerHTML = '<tr><td colspan="6" class="table-empty">No certificates issued yet.</td></tr>';
    } else {
      // Load each certificate's details
      for (const id of certIds) {
        try {
          const certData = await contract.getCertificate(id);
          const isRevoked = certData[8]; // revoked field

          const row = document.createElement("tr");
          row.innerHTML = `
            <td style="font-family:var(--font-mono); font-size:0.8rem;">${escapeHtml(certData[0])}</td>
            <td>${escapeHtml(certData[1])}</td>
            <td>${escapeHtml(certData[3])}</td>
            <td>${escapeHtml(certData[5])}</td>
            <td>
              ${isRevoked
                ? '<span class="badge badge-danger">⚠ Revoked</span>'
                : '<span class="badge badge-success">✓ Active</span>'
              }
            </td>
            <td>
              ${!isRevoked
                ? `<button class="btn btn-danger" onclick="revokeFromTable('${escapeHtml(certData[0])}')">
                    🚫 Revoke
                  </button>`
                : '<span style="color:var(--text-muted); font-size:0.78rem;">Revoked</span>'
              }
            </td>
          `;
          tbody.appendChild(row);
        } catch (certErr) {
          console.error("Error loading cert:", id, certErr);
        }
      }
    }

  } catch (err) {
    console.error("Dashboard error:", err);
  } finally {
    hideElement("adminLoading");
  }
}

/**
 * Fills in the revoke input and calls revokeCertificate when clicking revoke in table.
 * @param {string} certId - Certificate ID to revoke
 */
function revokeFromTable(certId) {
  document.getElementById("revokeCertId").value = certId;
  document.getElementById("revokeCertId").scrollIntoView({ behavior: "smooth" });
  revokeCertificate();
}

/**
 * Revokes a certificate on the blockchain.
 */
async function revokeCertificate() {
  const certId = document.getElementById("revokeCertId").value.trim();

  if (!certId) {
    showAlert("revokeError", "revokeErrorText", "Please enter a Certificate ID to revoke.");
    return;
  }

  if (!isContractOwner || !contract) {
    showAlert("revokeError", "revokeErrorText", "Only the admin wallet can revoke certificates.");
    return;
  }

  // Confirm before revoking
  const confirmed = window.confirm(
    `Are you sure you want to revoke certificate "${certId}"?\n\nThis action is permanent and cannot be undone.`
  );
  if (!confirmed) return;

  hideAlert("revokeError");
  hideAlert("revokeSuccess");
  showElement("revokeLoading");
  document.getElementById("btnRevoke").disabled = true;

  try {
    const tx = await contract.revokeCertificate(certId);
    await tx.wait(1);

    hideElement("revokeLoading");

    showAlert(
      "revokeSuccess",
      "revokeSuccessText",
      `Certificate "${certId}" has been revoked successfully. TX: ${tx.hash}`
    );

    // Reload dashboard
    await loadAdminDashboard();

  } catch (err) {
    hideElement("revokeLoading");
    showAlert("revokeError", "revokeErrorText", getFriendlyError(err));
    console.error("Revoke error:", err);
  } finally {
    document.getElementById("btnRevoke").disabled = false;
  }
}

