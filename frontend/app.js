/**
 * Called when the page loads.
 * Loads contract config, checks MetaMask, and sets up event listeners.
 */
document.addEventListener("DOMContentLoaded", async function () {
  // Load contract configuration from contract-config.js
  loadContractConfig();

  // Set up form events
  setupEventListeners();

  // Check if MetaMask is already connected from a previous session
  await checkExistingConnection();

  // Update About page with contract info
  updateAboutSection();

  console.log("🔗 BlockCert DApp initialized.");
  console.log("📄 Contract Address:", contractAddress);
  console.log("👤 Expected Owner:", ownerAddress);
});

/**
 * Loads the contract address and ABI from contract-config.js.
 * This file is auto-generated by scripts/deploy.js.
 */
function loadContractConfig() {
  try {
    // These variables come from contract-config.js loaded in index.html
    if (typeof CONTRACT_ADDRESS !== "undefined") {
      contractAddress = CONTRACT_ADDRESS;
    }
    if (typeof CONTRACT_ABI !== "undefined") {
      contractABI = CONTRACT_ABI;
    }
    if (typeof OWNER_ADDRESS !== "undefined") {
      ownerAddress = OWNER_ADDRESS;
    }
    if (typeof CHAIN_ID !== "undefined") {
      expectedChainId = CHAIN_ID;
    }
  } catch (err) {
    console.warn("Could not load contract-config.js:", err);
  }

  if (!contractAddress || contractAddress === "0x0000000000000000000000000000000000000000") {
    console.warn("Contract not deployed yet. Deploy the contract and refresh.");
  }
}

/**
 * Sets up all form event listeners.
 */
function setupEventListeners() {
  // Issue Certificate Form
  const issueForm = document.getElementById("issueCertForm");
  if (issueForm) {
    issueForm.addEventListener("submit", function (e) {
      e.preventDefault();
      issueCertificate();
    });
  }

  // Certificate file upload — auto-generate hash
  const issueFile = document.getElementById("issueCertFile");
  if (issueFile) {
    issueFile.addEventListener("change", function () {
      if (this.files && this.files[0]) {
        generateFileHash(this.files[0], "issueCertHashValue", "issueHashDisplay", "certHash");
      }
    });
  }

  // File drop event for issue form
  const issueFileArea = document.getElementById("issueFileArea");
  if (issueFileArea) {
    issueFileArea.addEventListener("dragover", (e) => {
      e.preventDefault();
      issueFileArea.classList.add("drag-over");
    });
    issueFileArea.addEventListener("dragleave", () => {
      issueFileArea.classList.remove("drag-over");
    });
    issueFileArea.addEventListener("drop", async (e) => {
      e.preventDefault();
      issueFileArea.classList.remove("drag-over");
      if (e.dataTransfer.files[0]) {
        generateFileHash(e.dataTransfer.files[0], "issueCertHashValue", "issueHashDisplay", "certHash");
      }
    });
  }

  // Nav link clicks
  document.querySelectorAll(".nav-links a[data-section]").forEach(function (link) {
    link.addEventListener("click", function (e) {
      e.preventDefault();
      showSection(this.getAttribute("data-section"));
    });
  });

  // Mobile nav toggle
  const navToggle = document.getElementById("navToggle");
  if (navToggle) {
    navToggle.addEventListener("click", function () {
      document.getElementById("navLinks").classList.toggle("open");
    });
  }
}

