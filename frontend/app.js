/**
 * Verifies an uploaded certificate file's hash against the blockchain.
 * Called when user uploads a file on the verify page.
 */
async function verifyFileHash() {
  const fileInput = document.getElementById("verifyCertFile");
  if (!fileInput || !fileInput.files || !fileInput.files[0]) return;

  const file = fileInput.files[0];
  const compareDiv = document.getElementById("hashCompareResult");
  const hashDisplay = document.getElementById("verifyHashDisplay");

  // Reset states
  compareDiv.classList.remove("visible", "match", "mismatch");
  hashDisplay.classList.remove("visible");

  try {
    // Calculate SHA-256 hash of the uploaded file
    const fileHash = await calculateSHA256(file);

    // Show the file hash
    document.getElementById("verifyFileHashValue").textContent = fileHash;
    hashDisplay.classList.add("visible");

    // Compare with blockchain hash
    const blockchainHash = lastVerifiedCertHash;

    compareDiv.classList.add("visible");

    if (!blockchainHash) {
      // No certificate was verified yet
      setCheckItem("checkBlockchain", false, "No certificate verified yet. Please verify a certificate first.");
      setCheckItem("checkHash", false, "Cannot compare hash.");
      setCheckItem("checkFinal", false, "Please verify a Certificate ID first.");
      compareDiv.classList.add("mismatch");
      return;
    }

    // Blockchain record found
    setCheckItem("checkBlockchain", true, "Blockchain record found");

    if (fileHash.toLowerCase() === blockchainHash.toLowerCase()) {
      // Hashes MATCH
      setCheckItem("checkHash", true, "Certificate hash matches blockchain record");
      setCheckItem("checkFinal", true, "✓ Certificate is authentic and has not been modified.");
      compareDiv.classList.add("match");
    } else {
      // Hashes DO NOT MATCH
      setCheckItem("checkHash", false, "Hash mismatch — file does not match blockchain record");
      setCheckItem("checkFinal", false, "✗ Certificate file has been modified or is not the original certificate.");
      compareDiv.classList.add("mismatch");
    }

  } catch (err) {
    console.error("File hash error:", err);
    setCheckItem("checkFinal", false, "Error processing file: " + err.message);
    compareDiv.classList.add("visible", "mismatch");
  }
}

/**
 * Sets a check item's icon and text in the hash comparison result.
 */
function setCheckItem(iconId, isOk, text) {
  const iconEl = document.getElementById(iconId);
  const textEl = document.getElementById(iconId + "Text");
  iconEl.textContent = isOk ? "✓" : "✗";
  iconEl.className   = "check-icon " + (isOk ? "ok" : "fail");
  if (textEl) textEl.textContent = text;
}

