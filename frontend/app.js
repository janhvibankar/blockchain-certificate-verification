/**
 * Calculates the SHA-256 hash of a file using the browser's Web Crypto API.
 * @param {File} file - The file to hash
 * @returns {Promise<string>} - Hex string of the SHA-256 hash
 */
async function calculateSHA256(file) {
  const arrayBuffer = await file.arrayBuffer();
  const hashBuffer  = await crypto.subtle.digest("SHA-256", arrayBuffer);
  const hashArray   = Array.from(new Uint8Array(hashBuffer));
  const hashHex     = hashArray.map(b => b.toString(16).padStart(2, "0")).join("");
  return hashHex;
}

/**
 * Generates a file's SHA-256 hash and displays it, then optionally updates an input field.
 * @param {File} file - File to hash
 * @param {string} displaySpanId - Element ID to show the hash value
 * @param {string} displayContainerId - Element ID of the hash display box
 * @param {string} inputFieldId - (Optional) Input field ID to auto-fill with the hash
 */
async function generateFileHash(file, displaySpanId, displayContainerId, inputFieldId) {
  try {
    const displaySpan  = document.getElementById(displaySpanId);
    const displayBox   = document.getElementById(displayContainerId);

    displaySpan.textContent = "Calculating hash...";
    displayBox.classList.add("visible");

    const hash = await calculateSHA256(file);

    displaySpan.textContent = hash;

    // Auto-fill the hash input if provided
    if (inputFieldId) {
      const inputEl = document.getElementById(inputFieldId);
      if (inputEl) inputEl.value = hash;
    }

    console.log("📄 File:", file.name, "| SHA-256:", hash);

  } catch (err) {
    console.error("Hash calculation error:", err);
    const displaySpan = document.getElementById(displaySpanId);
    if (displaySpan) displaySpan.textContent = "Error calculating hash: " + err.message;
  }
}

