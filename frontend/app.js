/**
 * Converts raw blockchain/MetaMask errors into human-friendly messages.
 * @param {Error} err - The error object
 * @returns {string} - A user-friendly error message
 */
function getFriendlyError(err) {
  if (!err) return "An unknown error occurred.";

  const message = err.message || err.toString();
  const data    = err.data?.message || "";
  const reason  = err.reason || "";

  // Combine all available error info
  const fullMsg = (message + " " + data + " " + reason).toLowerCase();

  // MetaMask user rejections
  if (err.code === 4001 || fullMsg.includes("user rejected") || fullMsg.includes("user denied")) {
    return "Transaction cancelled. You rejected the transaction in MetaMask.";
  }

  // Duplicate certificate
  if (fullMsg.includes("certificate id already exists") || fullMsg.includes("already exists")) {
    return "Certificate ID already exists. Please use a unique Certificate ID.";
  }

  // Unauthorized
  if (fullMsg.includes("only the institute admin") || fullMsg.includes("access denied")) {
    return "Access denied. Only the institute admin wallet can perform this action.";
  }

  // Already revoked
  if (fullMsg.includes("already revoked")) {
    return "This certificate is already revoked.";
  }

  // Not found
  if (fullMsg.includes("certificate not found")) {
    return "Certificate not found on the blockchain.";
  }

  // Empty field errors
  if (fullMsg.includes("cannot be empty")) {
    if (fullMsg.includes("certificate id")) return "Certificate ID cannot be empty.";
    if (fullMsg.includes("student name"))   return "Student name cannot be empty.";
    if (fullMsg.includes("certificate hash")) return "Certificate hash cannot be empty.";
    return "A required field is empty.";
  }

  // Network errors
  if (fullMsg.includes("network") || fullMsg.includes("provider") || fullMsg.includes("connection")) {
    return "Network error. Make sure the Hardhat local node is running (npx hardhat node) and MetaMask is connected to http://127.0.0.1:8545.";
  }

  // Out of gas
  if (fullMsg.includes("out of gas")) {
    return "Transaction ran out of gas. Please try again.";
  }

  // Contract not deployed
  if (fullMsg.includes("contract not deployed") || fullMsg.includes("no contract")) {
    return "Smart contract not found. Please run: npx hardhat run scripts/deploy.js --network localhost";
  }

  // RPC errors
  if (fullMsg.includes("rpc") || fullMsg.includes("http://127.0.0.1:8545")) {
    return "Cannot connect to local blockchain. Make sure 'npx hardhat node' is running in a terminal.";
  }

  // Generic fallback — show a clean message
  if (reason) return reason;
  if (data)   return "Transaction failed: " + data;

  return "An error occurred. Please check your MetaMask connection and try again.";
}

