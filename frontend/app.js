/**
 * Connects MetaMask wallet.
 * Called when user clicks "Connect Wallet" button.
 */
async function connectWallet() {
  // Check if MetaMask is installed
  if (!isMetaMaskInstalled()) {
    showMetaMaskInstallMessage();
    return;
  }

  try {
    // Request wallet connection
    provider = new ethers.BrowserProvider(window.ethereum);
    const accounts = await provider.send("eth_requestAccounts", []);

    if (accounts.length === 0) {
      showGlobalError("No accounts found. Please unlock MetaMask.");
      return;
    }

    await handleAccountsChanged(accounts);

    // Listen for account changes
    window.ethereum.on("accountsChanged", handleAccountsChanged);

    // Listen for network/chain changes
    window.ethereum.on("chainChanged", handleChainChanged);

  } catch (err) {
    if (err.code === 4001) {
      // User rejected the connection request
      showGlobalError("Connection rejected. Please click 'Connect Wallet' and approve in MetaMask.");
    } else {
      showGlobalError("Failed to connect wallet: " + getFriendlyError(err));
    }
  }
}

/**
 * Checks if MetaMask is already connected (from a previous session).
 */
async function checkExistingConnection() {
  if (!isMetaMaskInstalled()) return;

  try {
    provider = new ethers.BrowserProvider(window.ethereum);
    const accounts = await provider.listAccounts();

    if (accounts.length > 0) {
      await handleAccountsChanged(accounts.map(a => a.address));

      // Listen for changes
      window.ethereum.on("accountsChanged", handleAccountsChanged);
      window.ethereum.on("chainChanged", handleChainChanged);
    }
  } catch (err) {
    console.log("No existing MetaMask connection:", err.message);
  }
}

/**
 * Handles wallet account changes (when user switches account in MetaMask).
 * @param {string[]} accounts - Array of connected account addresses
 */
async function handleAccountsChanged(accounts) {
  if (!accounts || accounts.length === 0) {
    // Wallet disconnected
    resetWalletState();
    return;
  }

  currentAccount = accounts[0];
  isWalletConnected = true;

  // Initialize contract with signer
  try {
    provider = new ethers.BrowserProvider(window.ethereum);
    signer   = await provider.getSigner();

    // Check network
    await checkNetwork();

    // Only initialize contract if config is loaded
    if (contractAddress && contractABI) {
      contract = new ethers.Contract(contractAddress, contractABI, signer);

      // Check if connected wallet is the contract owner
      try {
        const contractOwner = await contract.getOwner();
        isContractOwner = currentAccount.toLowerCase() === contractOwner.toLowerCase();
      } catch (err) {
        isContractOwner = false;
      }
    } else {
      isContractOwner = false;
    }
  } catch (err) {
    console.error("Error initializing contract:", err);
    isContractOwner = false;
  }

  updateWalletUI();
  updateIssuePageState();
}

/**
 * Handles network/chain changes.
 * @param {string} chainId - New chain ID in hex
 */
function handleChainChanged(chainId) {
  // Reload the page on chain change (recommended by MetaMask docs)
  window.location.reload();
}

/**
 * Resets the UI to disconnected state.
 */
function resetWalletState() {
  currentAccount    = null;
  isWalletConnected = false;
  isContractOwner   = false;
  provider = null;
  signer   = null;
  contract = null;
  updateWalletUI();
}

/**
 * Updates the wallet status display in the navbar.
 */
function updateWalletUI() {
  const dot         = document.getElementById("walletDot");
  const addrSpan    = document.getElementById("walletAddress");
  const connectBtn  = document.getElementById("btnConnectWallet");

  if (isWalletConnected && currentAccount) {
    dot.classList.add("connected");
    addrSpan.textContent = shortenAddress(currentAccount);
    connectBtn.textContent = "✓ Connected";
    connectBtn.style.background = "rgba(16,185,129,0.15)";
    connectBtn.style.border = "1px solid rgba(16,185,129,0.4)";
    connectBtn.style.color = "#34d399";
  } else {
    dot.classList.remove("connected");
    addrSpan.textContent = "Not Connected";
    connectBtn.textContent = "🦊 Connect Wallet";
    connectBtn.style.background = "";
    connectBtn.style.border = "";
    connectBtn.style.color = "";
  }

  // Update about section owner info
  if (document.getElementById("aboutOwner")) {
    document.getElementById("aboutOwner").textContent = ownerAddress || "Deploy contract first";
  }
}

/**
 * Checks if the connected network is the expected Hardhat network.
 */
async function checkNetwork() {
  if (!provider || !expectedChainId) return;

  try {
    const network = await provider.getNetwork();
    const currentChainId = Number(network.chainId);

    if (currentChainId !== expectedChainId) {
      document.getElementById("networkAlert").classList.add("visible");
    } else {
      document.getElementById("networkAlert").classList.remove("visible");
    }
  } catch (err) {
    console.error("Error checking network:", err);
  }
}

/**
 * Updates the Issue Certificate page based on wallet/admin state.
 */
function updateIssuePageState() {
  const metamaskWarning = document.getElementById("issueMetamaskWarning");
  const notAdminAlert   = document.getElementById("notAdminAlert");

  if (!isMetaMaskInstalled()) {
    metamaskWarning.classList.add("visible");
    notAdminAlert.classList.remove("visible");
    return;
  }

  metamaskWarning.classList.remove("visible");

  if (!isWalletConnected) {
    notAdminAlert.classList.remove("visible");
    return;
  }

  if (!isContractOwner) {
    notAdminAlert.classList.add("visible");
  } else {
    notAdminAlert.classList.remove("visible");
  }
}

