/**
 * Issues a new certificate on the blockchain.
 * Called when the issue form is submitted.
 */
async function issueCertificate() {
  // --- Pre-checks ---
  if (!isMetaMaskInstalled()) {
    showAlert("issueError", "issueErrorText", "Please install MetaMask to issue certificates.");
    return;
  }

  if (!isWalletConnected) {
    showAlert("issueError", "issueErrorText", "Please connect your MetaMask wallet first.");
    return;
  }

  if (!isContractOwner) {
    showAlert("issueError", "issueErrorText", "Access denied. Only the institute admin wallet can issue certificates. Please switch to the admin account in MetaMask.");
    return;
  }

  if (!contract) {
    showAlert("issueError", "issueErrorText", "Smart contract not initialized. Please deploy the contract and refresh the page.");
    return;
  }

  // --- Read form values ---
  const certId      = document.getElementById("certId").value.trim();
  const studentName = document.getElementById("studentName").value.trim();
  const studentEmail= document.getElementById("studentEmail").value.trim();
  const courseName  = document.getElementById("courseName").value.trim();
  const instituteName = document.getElementById("instituteName").value.trim();
  const issueDate   = document.getElementById("issueDate").value.trim();
  const certHash    = document.getElementById("certHash").value.trim();

  // --- Frontend Validation ---
  if (!certId) {
    showAlert("issueError", "issueErrorText", "Certificate ID is required.");
    document.getElementById("certId").focus();
    return;
  }
  if (!studentName) {
    showAlert("issueError", "issueErrorText", "Student Name is required.");
    return;
  }
  if (!studentEmail || !studentEmail.includes("@")) {
    showAlert("issueError", "issueErrorText", "Please enter a valid student email address.");
    return;
  }
  if (!courseName) {
    showAlert("issueError", "issueErrorText", "Course Name is required.");
    return;
  }
  if (!instituteName) {
    showAlert("issueError", "issueErrorText", "Institute Name is required.");
    return;
  }
  if (!issueDate) {
    showAlert("issueError", "issueErrorText", "Issue Date is required.");
    return;
  }
  if (!certHash) {
    showAlert("issueError", "issueErrorText", "Certificate Hash is required. Please upload a certificate file to generate the hash, or enter it manually.");
    return;
  }

  // Hide previous errors
  hideAlert("issueError");
  hideElement("issueTxInfo");

  // Show loading
  showElement("issueLoading");
  document.getElementById("btnIssueCert").disabled = true;

  try {
    document.getElementById("issueLoadingText").textContent = "Waiting for MetaMask approval...";

    // Call the smart contract
    const tx = await contract.issueCertificate(
      certId,
      studentName,
      studentEmail,
      courseName,
      instituteName,
      issueDate,
      certHash
    );

    document.getElementById("issueLoadingText").textContent = "Transaction submitted. Waiting for confirmation...";

    // Wait for 1 block confirmation
    const receipt = await tx.wait(1);

    // Show success information
    hideElement("issueLoading");

    document.getElementById("txCertId").textContent   = certId;
    document.getElementById("txHash").textContent     = tx.hash;
    document.getElementById("txIssuer").textContent   = currentAccount;
    document.getElementById("txCertHash").textContent = certHash;
    document.getElementById("txBlock").textContent    = receipt.blockNumber.toString();

    showElement("issueTxInfo");

    console.log("✅ Certificate issued. TX:", tx.hash);

  } catch (err) {
    hideElement("issueLoading");

    const friendlyMsg = getFriendlyError(err);
    showAlert("issueError", "issueErrorText", friendlyMsg);
    console.error("Issue certificate error:", err);

  } finally {
    document.getElementById("btnIssueCert").disabled = false;
  }
}

