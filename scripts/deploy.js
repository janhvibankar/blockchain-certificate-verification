/**
 * deploy.js
 *
 * Deploys the CertificateVerification smart contract to the configured network.
 * After deployment, it automatically saves the contract address and ABI so
 * the frontend can use them without any manual copy-pasting.
 *
 * Run with:
 *   npx hardhat run scripts/deploy.js --network localhost
 *   (Make sure `npx hardhat node` is running in another terminal first)
 */

const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("\n========================================");
  console.log("  Deploying CertificateVerification...  ");
  console.log("========================================\n");

  // Get the deployer's account (first account from Hardhat node)
  const [deployer] = await ethers.getSigners();
  console.log("Deploying contract with account:", deployer.address);

  const balance = await ethers.provider.getBalance(deployer.address);
  console.log("Account balance:", ethers.formatEther(balance), "ETH\n");

  // Compile and get the contract factory
  const CertificateVerification = await ethers.getContractFactory("CertificateVerification");

  // Deploy the contract
  console.log("Deploying contract...");
  const contract = await CertificateVerification.deploy();
  await contract.waitForDeployment();

  const contractAddress = await contract.getAddress();

  console.log("\n✅ Contract deployed successfully!");
  console.log("📄 Contract Address:", contractAddress);
  console.log("👤 Owner/Admin Address:", deployer.address);
  console.log("🌐 Network: Hardhat Local (Chain ID 31337)");
  console.log("🔗 RPC URL: http://127.0.0.1:8545\n");

  // ----------------------------------------------------------------
  // Save contract address to deployments/contract-address.json
  // ----------------------------------------------------------------
  const deploymentsDir = path.join(__dirname, "..", "deployments");
  if (!fs.existsSync(deploymentsDir)) {
    fs.mkdirSync(deploymentsDir, { recursive: true });
  }

  const deploymentInfo = {
    contractAddress: contractAddress,
    ownerAddress: deployer.address,
    network: "localhost",
    chainId: 31337,
    rpcUrl: "http://127.0.0.1:8545",
    deployedAt: new Date().toISOString(),
  };

  fs.writeFileSync(
    path.join(deploymentsDir, "contract-address.json"),
    JSON.stringify(deploymentInfo, null, 2)
  );
  console.log("💾 Saved deployment info to deployments/contract-address.json");

  // ----------------------------------------------------------------
  // Save ABI + address to frontend/contract-config.js
  // This file is imported by app.js so the frontend always has the
  // correct address and ABI without any manual copy-pasting.
  // ----------------------------------------------------------------
  const artifactPath = path.join(
    __dirname,
    "..",
    "artifacts",
    "contracts",
    "CertificateVerification.sol",
    "CertificateVerification.json"
  );

  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  const abi = artifact.abi;

  const frontendDir = path.join(__dirname, "..", "frontend");
  if (!fs.existsSync(frontendDir)) {
    fs.mkdirSync(frontendDir, { recursive: true });
  }

  const configContent = `// AUTO-GENERATED by scripts/deploy.js - DO NOT EDIT MANUALLY
// This file is automatically updated every time you deploy the contract.
// Last deployed: ${new Date().toISOString()}

const CONTRACT_ADDRESS = "${contractAddress}";
const OWNER_ADDRESS = "${deployer.address}";
const CHAIN_ID = 31337;
const NETWORK_NAME = "Hardhat Local Network";
const RPC_URL = "http://127.0.0.1:8545";

const CONTRACT_ABI = ${JSON.stringify(abi, null, 2)};
`;

  fs.writeFileSync(path.join(frontendDir, "contract-config.js"), configContent);
  console.log("💾 Saved contract config to frontend/contract-config.js");

  console.log("\n========================================");
  console.log("  NEXT STEPS:");
  console.log("========================================");
  console.log("1. Add Hardhat Local Network to MetaMask:");
  console.log("   Network Name: Hardhat Local");
  console.log("   RPC URL:      http://127.0.0.1:8545");
  console.log("   Chain ID:     31337");
  console.log("   Currency:     ETH");
  console.log("");
  console.log("2. Import this admin account to MetaMask:");
  console.log("   Address:", deployer.address);
  console.log("   (Use Hardhat's test private key from the node terminal)");
  console.log("");
  console.log("3. Open frontend/index.html in your browser");
  console.log("   (Use VS Code Live Server extension)");
  console.log("========================================\n");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("❌ Deployment failed:", error);
    process.exit(1);
  });
